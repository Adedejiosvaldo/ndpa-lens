// Solar icons (Iconify, CC BY 4.0, by 480 Design) → a small generated module,
// so only the icons we use ship to the browser. Run: pnpm icons
import { writeFileSync } from "node:fs";
import { icons } from "@iconify-json/solar";
import { getIconData, iconToSVG } from "@iconify/utils";

const NAMES = [
  "arrow-right-linear",
  "arrow-left-linear",
  "alt-arrow-down-linear",
  "document-text-linear",
  "checklist-minimalistic-linear",
  "globus-linear",
  "fingerprint-linear",
  "users-group-two-rounded-linear",
  "lock-keyhole-minimalistic-linear",
  "calendar-linear",
  "magnifer-linear",
  "check-circle-linear",
  "danger-triangle-linear",
  "file-check-linear",
  "server-square-linear",
  "key-minimalistic-linear",
  "history-linear",
  "refresh-linear",
  "copy-linear",
  "download-minimalistic-linear",
  "logout-2-linear",
  "user-plus-linear",
  "trash-bin-minimalistic-linear",
  "qr-code-linear",
  "letter-linear",
  "case-minimalistic-linear",
  "eye-linear",
  "pen-new-square-linear",
  "monitor-smartphone-linear",
  "map-point-wave-linear",
  "sledgehammer-linear",
  "diploma-verified-linear",
  "justice-scale-linear",
];

const out = {};
for (const n of NAMES) {
  const data = getIconData(icons, n);
  if (!data) throw new Error(`Unknown Solar icon: ${n}`);
  const svg = iconToSVG(data);
  out[n] = { body: svg.body, viewBox: svg.attributes.viewBox };
}
writeFileSync(
  new URL("../src/components/icons.generated.ts", import.meta.url),
  `// Generated by scripts/build-icons.mjs — do not edit. Solar icons by 480 Design, CC BY 4.0 (via Iconify).\nexport const ICONS = ${JSON.stringify(out, null, 0)} as const;\nexport type IconName = keyof typeof ICONS;\n`,
);
console.log(`Wrote ${NAMES.length} icons`);
