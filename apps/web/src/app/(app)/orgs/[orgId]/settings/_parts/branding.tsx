"use client";

import { useEffect, useRef, useState } from "react";
import { useApiForm } from "@/components/use-form";
import { Button } from "@/components/ui/button";
import { Alert, PageSection } from "@/components/ui/card";
import { Field } from "@/components/ui/field";
import { api, ApiError, type Branding, type Org, RawBody } from "@/lib/api";

const MAX_LOGO = 1024 * 1024;

/** The pack cover as the DPCO's clients will see it (BRAND-01, BRAND-02). */
function CoverPreview({ b, org, logoUrl }: { b: Omit<Branding, "logo" | "logoUrl">; org: Org; logoUrl: string | null }) {
  return (
    <figure className="w-full max-w-[300px]" aria-label="Pack cover preview">
      <div className="aspect-[1/1.414] rounded-md bg-white p-6 text-[#0b0d12] shadow-[var(--shadow-lift)]">
        <div className="flex min-h-8 items-center gap-2">
          {logoUrl ? (
            <img src={logoUrl} alt={`${b.firmName || org.name} logo`} width={96} height={32} className="h-8 w-auto max-w-[120px] object-contain" />
          ) : null}
          <span className="text-sm font-semibold break-words" style={{ color: b.primaryColour }}>
            {b.firmName || org.name}
          </span>
        </div>
        <p className="mt-12 text-[10px] text-[#4b5563]">NDPA technical evidence pack</p>
        <p className="text-lg leading-tight font-semibold">Your client's name</p>
        <div className="mt-6 h-1 w-12 rounded" style={{ background: b.primaryColour }} />
        {b.showLicenceOnCover && org.dpcoLicenceNo && <p className="mt-6 text-[10px] text-[#4b5563]">DPCO licence {org.dpcoLicenceNo}</p>}
        {b.contactBlock && <p className="mt-2 text-[10px] whitespace-pre-line text-[#4b5563]">{b.contactBlock}</p>}
        <p className="mt-6 text-[8px] text-[#4b5563]">Technical evidence generated by NDPA Lens</p>
      </div>
      <figcaption className="mt-2 text-xs text-muted">Live preview of your pack cover</figcaption>
    </figure>
  );
}

export function BrandingSection({ org, canEdit }: { org: Org; canEdit: boolean }) {
  const [b, setB] = useState<Branding | null>(null);
  const [saved, setSaved] = useState(false);
  const [logoError, setLogoError] = useState<string | null>(null);
  const [uploading, setUploading] = useState(false);
  const fileRef = useRef<HTMLInputElement>(null);
  const { busy, error, fields, run } = useApiForm();

  useEffect(() => {
    void api.get<Branding>(`/v1/orgs/${org.id}/branding`).then(setB);
  }, [org.id]);
  if (!b) return null;

  async function onLogo(file: File | undefined) {
    if (!file) return;
    setLogoError(null);
    if (!["image/png", "image/svg+xml"].includes(file.type)) return setLogoError("Upload a PNG or SVG.");
    if (file.size > MAX_LOGO) return setLogoError("Logos can be at most 1 MB.");
    setUploading(true);
    try {
      setB(await api.put<Branding>(`/v1/orgs/${org.id}/branding/logo`, new RawBody(file, file.type)));
    } catch (e) {
      setLogoError(e instanceof ApiError ? (e.detail ?? e.message) : "The upload failed. Try again.");
    } finally {
      setUploading(false);
      if (fileRef.current) fileRef.current.value = "";
    }
  }

  return (
    <PageSection title="Pack branding" description="Your clients see your brand on every evidence pack. NDPA Lens appears only as one small line.">
      <div className="grid gap-10 lg:grid-cols-[minmax(0,1fr)_300px]">
        <form
          className="max-w-lg space-y-4"
          onSubmit={(e) => {
            e.preventDefault();
            void run(async () => {
              setB(
                await api.put<Branding>(`/v1/orgs/${org.id}/branding`, {
                  firmName: b.firmName || org.name,
                  primaryColour: b.primaryColour,
                  contactBlock: b.contactBlock,
                  showLicenceOnCover: b.showLicenceOnCover,
                }),
              );
              setSaved(true);
            });
          }}
        >
          {saved && <Alert tone="ok">Branding saved.</Alert>}
          {error && <Alert tone="error">{error}</Alert>}
          <fieldset disabled={!canEdit} className="space-y-4">
            <div className="space-y-1">
              <label htmlFor="logo-input" className="block text-sm font-medium">
                Logo
              </label>
              <div className="flex items-center gap-3">
                <input
                  ref={fileRef}
                  id="logo-input"
                  type="file"
                  accept="image/png,image/svg+xml"
                  aria-describedby="logo-hint"
                  className="sr-only"
                  onChange={(e) => onLogo(e.target.files?.[0])}
                />
                <Button variant="secondary" disabled={uploading || !canEdit} onClick={() => fileRef.current?.click()}>
                  {uploading ? "Uploading…" : b.logo ? "Replace logo" : "Upload logo"}
                </Button>
                <span id="logo-hint" className="text-xs text-muted">PNG or SVG, up to 1 MB</span>
              </div>
              {logoError && (
                <p role="alert" className="text-xs text-[var(--sev-critical)]">
                  {logoError}
                </p>
              )}
            </div>
            <Field label="Firm name on the cover" value={b.firmName} placeholder={org.name} onChange={(e) => setB({ ...b, firmName: e.target.value })} error={fields.firmName} />
            <div className="space-y-1">
              <label htmlFor="brand-colour" className="block text-sm font-medium">
                Brand colour
              </label>
              <div className="flex items-center gap-3">
                <input id="brand-colour" type="color" value={b.primaryColour} onChange={(e) => setB({ ...b, primaryColour: e.target.value })} className="h-10 w-14 cursor-pointer rounded border border-border bg-bg" />
                <span className="font-mono text-sm">{b.primaryColour}</span>
              </div>
              {fields.primaryColour && <p className="text-xs text-[var(--sev-critical)]">{fields.primaryColour}</p>}
            </div>
            <div className="space-y-1">
              <label htmlFor="contact-block" className="block text-sm font-medium">
                Contact block
              </label>
              <textarea
                id="contact-block"
                rows={3}
                maxLength={500}
                value={b.contactBlock}
                onChange={(e) => setB({ ...b, contactBlock: e.target.value })}
                placeholder={"12 Awolowo Road, Ikoyi, Lagos\naudits@yourfirm.ng"}
                className="w-full rounded-md border border-border bg-bg px-3 py-2 text-sm"
              />
            </div>
            <label className="flex items-center gap-2 text-sm">
              <input type="checkbox" checked={b.showLicenceOnCover} onChange={(e) => setB({ ...b, showLicenceOnCover: e.target.checked })} />
              Show our DPCO licence number on the cover
            </label>
          </fieldset>
          {canEdit && (
            <Button type="submit" disabled={busy}>
              Save branding
            </Button>
          )}
        </form>
        <CoverPreview b={b} org={org} logoUrl={b.logoUrl} />
      </div>
    </PageSection>
  );
}
